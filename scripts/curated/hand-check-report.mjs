// Lists every curated university with something we couldn't confirm from an
// official page (no tuition fee, or notes saying "Needs hand-checking" or
// "not confirmed"), so a person can finish them by hand. Generated from the
// CSV, so the list never drifts from the data:
//
//   node scripts/curated/hand-check-report.mjs   → docs/HAND-CHECK.md
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseCsv } from "./csv.mjs";

const ROOT = join(import.meta.dirname, "..", "..");
const rows = parseCsv(readFileSync(join(ROOT, "data", "curated", "international_universities.csv"), "utf8"));
const open = rows.filter((r) => r.tuition_local === "" || /needs hand-checking|not confirmed/i.test(r.notes));
// What to finish: the note when there is one, else the empty fee.
const missing = (r) =>
  /needs hand-checking|not confirmed/i.test(r.notes)
    ? r.notes.replace(/^.*?(Needs hand-checking: )/i, "$1")
    : `International tuition fee not available${r.notes ? ` (${r.notes})` : ""}`;

const byCountry = new Map();
for (const r of open) byCountry.set(r.country, [...(byCountry.get(r.country) ?? []), r]);
const countries = [...byCountry.keys()].sort();

// Markdown table cells can't contain a pipe or a line break.
const cell = (s) => String(s ?? "").replace(/\|/g, "/").replace(/\s+/g, " ").trim();

const lines = [
  "# Universities that need hand-checking",
  "",
  "Generated by `node scripts/curated/hand-check-report.mjs` from `data/curated/international_universities.csv`; don't edit by hand.",
  "",
  "Each row below is missing something we couldn't confirm on an official page: usually the international tuition fee (the site blocks automated fetching, the fee is in a PDF or a calculator, or the page gives no figure for the year), sometimes the degree levels. The field is left empty (shown as \"Not available\") rather than guessed. To finish one: open the official page, record the figure with its basis, year, link and the date you checked it in the CSV, remove the note, and re-run `npm run data:build-international`.",
  "",
  `**${open.length} of ${rows.length}** curated universities, in ${countries.length} countries.`,
  "",
];
for (const country of countries) {
  const list = byCountry.get(country).sort((a, b) => a.name.localeCompare(b.name));
  lines.push(`## ${country} (${list.length})`, "", "| University | Website | What's missing |", "| --- | --- | --- |");
  for (const r of list) lines.push(`| ${cell(r.name)} | ${cell(r.source_url)} | ${cell(missing(r))} |`);
  lines.push("");
}
writeFileSync(join(ROOT, "docs", "HAND-CHECK.md"), lines.join("\n"));
console.log(`Wrote docs/HAND-CHECK.md: ${open.length} of ${rows.length} universities in ${countries.length} countries.`);
